/**
 * UNIVERSITY DATASET — rebuilt from user-provided QIF (exact questions/marks).
 * 7 Criteria, 34 KIs, 36 QlM + 79 QnM = 115 Metrics. Every metric independent.
 */
function m(
  id: string, kiId: string, criterionId: number, title: string,
  type: 'QlM' | 'QnM', weightage: number, description: string,
  dataRequired: string[], documents: string[], tables: { title: string; columns: string[]; helpText?: string }[],
  extra: Partial<Metric> = {}
): Metric {
  return {
    id, uid: `univ:${id}`, kiId, criterionId,
    title: String(title), type, weightage, description: String(description),
    dataRequired: [...dataRequired],
    subQuestions: extra.subQuestions ? extra.subQuestions.map((s) => ({ id: String(s.id), text: String(s.text) })) : undefined,
    fileDescription: extra.fileDescription ? [...extra.fileDescription] : undefined,
    dataTemplateFields: extra.dataTemplateFields ? [...extra.dataTemplateFields] : undefined,
    wordLimit: extra.wordLimit,
    options: extra.options ? [...extra.options] : undefined,
    formula: extra.formula,
    documentsRequired: documents.map((d, i) => ({ name: String(d), required: i === 0 })),
    supportingEvidence: extra.supportingEvidence ? [...extra.supportingEvidence] : [],
    tables: tables.map((t) => ({ title: String(t.title), columns: [...t.columns], helpText: t.helpText })),
    linksRequired: extra.linksRequired ? [...extra.linksRequired] : [],
    notes: extra.notes ? [...extra.notes] : [],
    dataPeriod: extra.dataPeriod ?? 'Last five years',
    optional: extra.optional ?? false,
    sourceManual: SM,
    sourceSection: extra.sourceSection ?? SS,
    sourcePage: NOT_SPECIFIED,
  };
}

